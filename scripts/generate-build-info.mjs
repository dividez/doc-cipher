import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repoRoot, 'packages/shared/src/build-info.ts');
const packageJsonPath = join(repoRoot, 'package.json');

const REPO_URL = 'https://github.com/dividez/doc-cipher';

function readPackageVersion() {
  const pkg = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
  return pkg.version ?? '0.0.0';
}

function resolveVersion() {
  const releaseTag = process.env.RELEASE_TAG?.trim();
  if (releaseTag) {
    return releaseTag.replace(/^v/i, '');
  }
  return readPackageVersion();
}

function formatTimestamp(date) {
  const pad = (n) => String(n).padStart(2, '0');
  return (
    [date.getFullYear(), pad(date.getMonth() + 1), pad(date.getDate())].join('') +
    '-' +
    [pad(date.getHours()), pad(date.getMinutes()), pad(date.getSeconds())].join('')
  );
}

function resolveBuild() {
  const sha = process.env.GITHUB_SHA?.trim();
  if (!sha) {
    return 'dev';
  }
  return `${formatTimestamp(new Date())}-${sha.slice(0, 7)}`;
}

function resolveCommit() {
  return process.env.GITHUB_SHA?.trim() || 'local';
}

function resolveLocalAiBundled() {
  const raw = process.env.DOCIPHER_BUNDLE_LLAMA?.trim().toLowerCase();
  if (raw === '1' || raw === 'true' || raw === 'yes') {
    return true;
  }
  if (raw === '0' || raw === 'false' || raw === 'no') {
    return false;
  }
  return false;
}

const BUILD_INFO = {
  version: resolveVersion(),
  build: resolveBuild(),
  commit: resolveCommit(),
  repo: REPO_URL,
  features: {
    localAi: resolveLocalAiBundled(),
  },
};

const contents = `// Auto-generated by scripts/generate-build-info.mjs — do not edit.
export const BUILD_INFO = ${JSON.stringify(BUILD_INFO, null, 2)} as const;

export type BuildInfo = typeof BUILD_INFO;
`;

writeFileSync(outputPath, contents, 'utf8');
console.log(`Generated ${outputPath}`);
console.log(`  version: ${BUILD_INFO.version}`);
console.log(`  build: ${BUILD_INFO.build}`);
console.log(`  features.localAi: ${BUILD_INFO.features.localAi}`);
